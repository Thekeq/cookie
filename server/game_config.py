# «Отдых»: XP дневного контента вернувшемуся после пропуска. Возвращенец
# (3 дня играет, 4 нет) отстаёт не потому, что играет хуже, а потому что
# дневной контент выдаётся посуточно: пропустил день — потерял его XP навсегда.
# Симуляция ловила это как «14 уровень при цели 15-20».
#
# Меряем именно ПРОПУЩЕННЫЕ ДНИ, а не отставание от кривой уровней: по кривой
# отстаёт и новичок, который заходит каждый день на пять минут, — но он ничего
# не терял, и доплата ему просто разгоняет его выше собственной цели (в
# симуляции — 12 уровень вместо цели 12-17 превращался в 16-18).
#
# Ставка ровно x1 за пропущенный день: бонус ВОЗВРАЩАЕТ потерянный XP, но
# никогда не платит больше, чем игрок получил бы, зайдя в те дни. Поэтому
# «полежать ради множителя» строго хуже игры — тем более что множится только XP
# уровня, а печеньки, BP XP, доход и прогресс заданий за пропуск теряются целиком.
LEVEL_REST_DAYS_CAP = 4         # больше четырёх пропущенных дней не копится
LEVEL_REST_PER_DAY = 1.0        # пропущенный день возвращается один к одному

def rest_mult(days_since_daily: float) -> float:
    """Множитель XP дневного контента по числу пропущенных дней (1.0 — играл
    вчера). Клики и рекорды тира не множатся: наверстать нужно ровно то, что
    выдаётся посуточно."""
    missed = min(max(0.0, days_since_daily - 1.0), float(LEVEL_REST_DAYS_CAP))
    return 1.0 + LEVEL_REST_PER_DAY * missed

