def recipe_state(key: str, elapsed_h: float) -> tuple[str, float]:
    """(состояние, множитель) для рецепта: rising | ready | burnt."""
    r = RECIPES.get(key)
    if not r:
        return "none", 1.0
    if elapsed_h < r["hours"]:
        return "rising", 1.0            # рано — тесто ещё не поднялось
    if elapsed_h <= r["hours"] * r["window"]:
        return "ready", r["mult"]       # в окне — полный множитель
    return "burnt", 1.0                 # передержал


