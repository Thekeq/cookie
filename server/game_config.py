"""Весь игровой баланс в одном месте — крутить числа тут."""

# ---------- Кликер ----------
MAX_CPS = 15                    # серверный потолок кликов/сек (анти-чит)
ENERGY_PER_CLICK = 1
# 0.45/сек: полный бак (400) за ~15 мин. Энергия должна КОНЧАТЬСЯ в сессии
# тапа (80 сек при 5 cps) — иначе апгрейды энергии бессмысленны (фидбек игроков)
ENERGY_REGEN_PER_SEC = 0.45

def max_energy(user_level: int) -> int:
    """Тесный бак: на 1 lvl хватает на ~80 сек тапа, качается уровнями и
    апгрейдами energy_cap — теперь их есть смысл покупать."""
    return 400 + (user_level - 1) * 50

# Сила клика — ДОЛЯ ЧАСОВОГО ДОХОДА, а не абсолютная экспонента.
#
# Абсолютная экспонента 1.55^(L-1) при потолке click_max_level(30) = 64 давала
# 1.55^63 = 9.8e11 за клик: игрок видел «4.5Т» и это число уже ничего ему не
# сообщало. Любая абсолютная кривая обречена на этот выбор: либо она отстаёт
# от пассивного дохода и клик умирает, либо обгоняет и уходит в бессмыслицу.
#
# Процент от дохода снимает выбор целиком: клик всегда сопоставим с фермой и
# доской, потому что считается ОТ них. В интерфейсе это читается как «клик =
# столько-то секунд твоего дохода» — величина, которую игрок понимает.
CLICK_SHARE_BASE = 0.00003      # доля часового дохода за один клик на 1 lvl
CLICK_SHARE_GROWTH = 1.05       # +5% доли за уровень прокачки
# Флор для новичка: пока фермы и доски нет, процент не от чего считать.
# Рост намеренно вялый (1.10, не 1.15): флор обязан ОСТАВАТЬСЯ флором. При
# 1.15 он давал на 64-м уровне 6 668 за клик и снова перебивал долю дохода —
# то есть абсолютная экспонента возвращалась через заднюю дверь.
CLICK_FLAT_BASE = 1.0
CLICK_FLAT_GROWTH = 1.10

def click_share(click_level: int) -> float:
    return CLICK_SHARE_BASE * (CLICK_SHARE_GROWTH ** (click_level - 1))

def click_power(click_level: int, base_income_per_hour: float = 0.0) -> float:
    """Сколько cookies даёт один клик.

    base_income_per_hour — доход БЕЗ учёта кликов (ферма + доска). Считать от
    полного hourly_income нельзя: тот сам включает оценку кликов, получилась бы
    рекурсия. Дефолт 0.0 оставлен, чтобы вызов без дохода отдавал честный флор.
    """
    return max(CLICK_FLAT_BASE * (CLICK_FLAT_GROWTH ** (click_level - 1)),
               base_income_per_hour * click_share(click_level))

# Цена апгрейда — тоже в часах дохода: абсолютная цена 1.8^n на 60-м уровне
# просила больше печенек, чем существует, а на 20-м была сдачей. Рост 1.015
# мягкий намеренно: настоящий гейт ветки — click_max_level (уровень игрока),
# а не деньги. Копить на апгрейд нужно, но недолго.
CLICK_COST_HOURS_BASE = 0.2
CLICK_COST_HOURS_GROWTH = 1.015

def click_upgrade_cost(click_level: int, base_income_per_hour: float = 0.0) -> float:
    """Цена прокачки клика с текущего уровня на следующий"""
    hours = CLICK_COST_HOURS_BASE * (CLICK_COST_HOURS_GROWTH ** (click_level - 1))
    return max(100 * (1.15 ** (click_level - 1)), base_income_per_hour * hours)

# Потолок прокачки клика по уровню игрока — тот же принцип, что req_level у
# зданий: одних денег мало, нужен прогресс. Без него жадная стратегия качает
# клик бесконечно и за 72 часа выносит 77 миллиардов (проверено симуляцией).
def click_max_level(user_level: int) -> int:
    return 4 + 2 * user_level

# ---------- Merge ----------
BOARD_SIZE = 25                 # сетка 5x5 (рисуется целиком, но не вся открыта)
MAX_ITEM_LEVEL = 24

# Клетки — дефицит (фидбек: «нет опасности, что закончатся клетки»).
# Базово открыто MERGE_BASE_CELLS, остальные — за уровни и приглашённых друзей.
MERGE_BASE_CELLS = 12
MERGE_CELL_LEVELS = (3, 5, 7, 9, 11, 13, 15, 18, 21)   # каждый уровень = +1 клетка
MERGE_CELL_REFS = (1, 3, 5, 10)                        # каждый порог друзей = +1 клетка

def merge_cells_unlocked(user_level: int, refs: int) -> int:
    cells = MERGE_BASE_CELLS
    cells += sum(1 for lvl in MERGE_CELL_LEVELS if user_level >= lvl)
    cells += sum(1 for need in MERGE_CELL_REFS if refs >= need)
    return min(cells, BOARD_SIZE)

# Цены доски. Раньше база спавна была income/40, где income включал ферму:
# ферма растёт экспоненциально, доход печеньки — константа, поэтому окупаемость
# предмета уезжала с 8 часов до 46 миллионов часов, и доска умирала.
#
# Ключевая математика: путь слияния до тира L стоит 2^(L-1) спавнов. Значит
# цена L1-спавна ОБЯЗАНА быть почти абсолютной — любая привязка к доходу
# умножается на 2^L и делает слияние в тысячи раз дороже прямой покупки, то
# есть убивает основной цикл. Поэтому:
#   L1-спавн   — константа x надбавка за заполненность доски;
#   прямая покупка тира — привязана к тому, СКОЛЬКО ПРЕДМЕТ ПРОИЗВОДИТ.
# Дефицит при этом создают КЛЕТКИ (их 12 базовых), а не бесконечная цена.
SPAWN_COST_GROWTH = 1.08        # каждая занятая клетка делает следующую дороже
SPAWN_L1_BASE = 50.0            # база спавна печеньки 1 уровня
# За столько часов окупается купленный тир. При PASSIVE_GROWTH = 2.0 это число
# честно держится на ВСЕХ тирах (см. комментарий у PASSIVE_GROWTH), поэтому оно
# и есть главная ручка сложности доски. 12 вместо 8: при 8 часах доход от
# полностью реинвестированной доски удваивался каждые ~5.5ч.
ITEM_PAYBACK_HOURS = 12.0

# Премия за рекорд тира. Доска физически ограничена (12-25 клеток и потолок
# тира по уровню), ферма — нет, поэтому без премии merge-цикл к середине игры
# давал 2-7% дохода и превращался в декорацию при живой ферме. Премия — ровно
# то, чего не хватало: множитель ко ВСЕЙ доске за каждый новый личный рекорд.
#
# Почему за рекорд, а не за мердж. Награда за каждое слияние умножилась бы на
# число спавнов (дерево слияния до тира L стоит 2^(L-1) спавнов) и доска
# разогналась бы сама — этим уже болел PASSIVE_GROWTH = 2.15. Рекорд берётся
# один раз за тир и вверх, поэтому премия ограничена сверху конструкцией:
# 1.10^21 ≈ 7.4 на максимальном тире, и больше не станет никогда.
MERGE_RECORD_BONUS = 0.10
MERGE_RECORD_FROM = 3           # с какого рекорда начисляется премия; тир 3 —
                                # опорный (на нём доход равен PASSIVE_BASE)

def record_multiplier(best_item_level: int) -> float:
    """Множитель дохода доски за личный рекорд тира."""
    steps = max(0, int(best_item_level or 0) - MERGE_RECORD_FROM)
    return (1.0 + MERGE_RECORD_BONUS) ** steps

# Окупаемость ПУТИ СЛИЯНИЯ. Отдельная ручка от ITEM_PAYBACK_HOURS, и без неё
# доска была печатным станком.
#
# ITEM_PAYBACK_HOURS управляет только ПРЯМОЙ покупкой тира. Но тот же доход
# собирается и слиянием — 2^(L-1) спавнов по SPAWN_L1_BASE, — а этот путь ничем
# не был ограничен. Арифметика: путь до тира L стоит 2^(L-1) спавнов, тир даёт
# PASSIVE_BASE * 2^(L-3), премия за рекорд стоит и в цене, и в доходе и потому
# сокращается. Остаётся 4 * SPAWN_L1_BASE / PASSIVE_BASE = 0.135 часа — ВОСЕМЬ
# МИНУТ окупаемости, одинаково на каждом тире, против 12 часов у прямой покупки.
# Разрыв в 90 раз, и именно он давал миллионы в час с доски при живой ферме:
# проектную цену игрок просто обходил основным циклом игры.
#
# Ровно половина ITEM_PAYBACK_HOURS: слияние ОБЯЗАНО остаться выгоднее прямой
# покупки — в этом весь смысл мердж-цикла, — но вдвое, а не в девяносто раз.
# Значение подтверждено перебором по balance_sim --matrix в паре с шагом cps
# фермы: эти две ручки работают только вместе.
MERGE_PAYBACK_HOURS = 6.0
# До какого рекорда тира цена спавна доезжает до полной. Новичку доска обязана
# остаться почти бесплатной: на рекорде 3 действует флор SPAWN_L1_BASE, дальше
# цена плавно доходит до проектной. Иначе первый спавн стоил бы 16 500 печенек
# игроку, у которого их ноль.
MERGE_PAYBACK_FULL_AT = 12

def merge_payback_hours(record: int) -> float:
    """Целевая окупаемость пути слияния при данном рекорде тира."""
    span = MERGE_PAYBACK_FULL_AT - MERGE_RECORD_FROM
    t = (int(record or 0) - MERGE_RECORD_FROM) / span
    return MERGE_PAYBACK_HOURS * min(1.0, max(0.0, t))

def _spawn_base(record: int) -> float:
    """База цены спавна без надбавок за клетки и рекорд.

    Делитель 4 — это 2^(L-1)/2^(L-3): во столько раз число спавнов пути слияния
    обгоняет доход собранного тира, одинаково на всех тирах."""
    return max(SPAWN_L1_BASE, merge_payback_hours(record) * PASSIVE_BASE / 4.0)

def spawn_cost(items_on_board: int, board_income_per_hour: float = 0.0,
               record: int = 0) -> float:
    """Цена спавна печеньки lvl1. board_income_per_hour оставлен в сигнатуре
    для совместимости вызовов и будущих правок — на цену L1 он не влияет.

    Премия за рекорд входит в цену ровно так же, как в доход: иначе она
    удешевляла бы весь путь слияния в те же 7.4 раза, окупаемость предмета
    падала бы с 12 часов до полутора, и доска снова стала бы печатным станком.
    С премией в обеих частях ITEM_PAYBACK_HOURS означает то, что написано в
    имени, на любом рекорде.

    База — не константа, а цена, выведенная из MERGE_PAYBACK_HOURS (см.
    _spawn_base). Флор SPAWN_L1_BASE держит старт: пока рекорд не дорос,
    работает он, и первые спавны стоят прежние 50."""
    return (_spawn_base(record) * (SPAWN_COST_GROWTH ** items_on_board)
            * record_multiplier(record))

def item_base_price(level: int, record: int = 0) -> float:
    """Сколько предмет производит за ITEM_PAYBACK_HOURS часов.

    Флор — стоимость пути слияния, а не SPAWN_L1_BASE. Тиры 1-2 дохода не дают,
    поэтому у них первый множитель нулевой, и на голом SPAWN_L1_BASE тир 2
    продавался по цене ОДНОГО спавна, хотя собирается из двух: прямая покупка
    выходила вдвое выгоднее слияния ровно там, где слияние и должно начинаться."""
    merge_path = 2 ** (level - 1) * _spawn_base(record)
    return max(merge_path,
               passive_income_per_hour(level) * ITEM_PAYBACK_HOURS) \
        * record_multiplier(record)

# топ-тиры только слиянием: напрямую можно купить максимум unlocked - 3
SPAWN_DIRECT_GAP = 3

def direct_spawn_cost(level: int, items_on_board: int,
                      board_income_per_hour: float = 0.0,
                      record: int = 0) -> float:
    """Прямая покупка тира: окупается за ITEM_PAYBACK_HOURS часов + та же
    надбавка за заполненность. Всегда дороже пути слияния — слияние выгоднее."""
    if level <= 1:
        return spawn_cost(items_on_board, board_income_per_hour, record)
    return (item_base_price(level, record)
            * (SPAWN_COST_GROWTH ** items_on_board))

# Мусорка/печь: перетащил печеньку — клетка освободилась, вернулась часть цены.
# Возврат считается от ФАКТИЧЕСКИ вложенного (board.paid), а не от текущей цены:
# иначе доска, собранная в бедности, переплавлялась бы по ценам богатого игрока
TRASH_REFUND = 0.10

def legacy_item_value(level: int) -> float:
    """Оценка вложенного для строк доски без paid (созданы до миграции).
    Считаем по пути слияния на пустой доске — щедрее не надо."""
    return SPAWN_L1_BASE * (2 ** (level - 1))

# XP за мердж делится на ДВА разных источника, и это принципиально.
#
# Раньше XP был один и рос как 10*2^(L-2). При суммировании по дереву слияний
# (чтобы собрать тир L, нужно 2^(L-1) спавнов) это давало ровно ~53 XP за
# КАЖДЫЙ спавн, независимо от того, что именно строишь. То есть XP был просто
# переименованными печеньками — а печеньки растут экспоненциально во времени.
# Уровень игрока при этом единственный гейт на тир предмета (item_unlock_level),
# и он падал целиком: 30-й уровень стоил ~5 500 спавнов ~ 1.4M печенек, минуты
# дохода прокачанной доски. Отсюда «друг апнул максимальный лвл за пару часов».
#
# Любой XP «за каждый мердж» неизбежно пропорционален числу спавнов — это
# свойство дерева, а не кривой. Поэтому объёмный XP оставлен намеренно мелким
# (рост 1.35 сильно ниже ветвления 2.0: вклад низких тиров затухает), а основа
# прогресса перенесена в first_item_xp — награду за ЛИЧНЫЙ РЕКОРД тира,
# которую по определению нельзя получить дважды и нельзя купить.
MERGE_VOLUME_XP_BASE = 4.0
MERGE_VOLUME_XP_GROWTH = 1.35
# Кап объёмного XP. Проверка «XP на спавн» его не ловит: на верхних тирах игрок
# покупает предмет напрямую, и один мердж 24 тира — это ОДНО действие, за
# которое без капа падало 3 420 XP. В зоне, где тир открывается каждый уровень
# (16-24), это давало цепную реакцию: рекорд -> уровень -> новый тир -> рекорд,
# и последние девять уровней брались за восемь часов. Действие есть действие,
# сколько бы ни стоил предмет.
MERGE_VOLUME_XP_CAP = 100.0

def merge_reward_xp(new_level: int) -> float:
    """XP за рядовой мердж — тонкий ручеёк «чтобы капало»."""
    return min(MERGE_VOLUME_XP_BASE * (MERGE_VOLUME_XP_GROWTH ** (new_level - 2)),
               MERGE_VOLUME_XP_CAP)

# Доля разрыва между уровнями, которую закрывает рекорд тира. Остальное игрок
# добирает временнЫм контентом: заказы, квесты, дейлики, дуэли, клики (у тех
# свой дневной кап). 0.5 держит баланс «половина за глубину, половина за игру».
FIRST_ITEM_XP_SHARE = 0.22

def first_item_xp(item_level: int) -> float:
    """XP за первое в жизни создание печеньки item_level.

    Считаем не с потолка, а от самой лестницы: тир открывается на уровне
    item_unlock_level(L), а помочь он должен дойти до уровня, который откроет
    СЛЕДУЮЩИЙ тир. Сумма всех рекордов телескопируется в FIRST_ITEM_XP_SHARE
    от всей ветки уровней — поэтому доля меняется одним числом и не требует
    пересчёта таблицы вручную."""
    here = xp_for_level(item_unlock_level(item_level))
    nxt_level = min(item_unlock_level(item_level + 1), MAX_LEVEL)
    gap = xp_for_level(nxt_level) - here
    if gap <= 0:
        # Верхний тир: следующего анлока не существует, разрыв схлопывается в
        # ноль. Отдаём шаг предыдущего тира — иначе главное достижение игры
        # (собрать MAX_ITEM_LEVEL) награждалось бы флором в 50 XP.
        gap = here - xp_for_level(item_unlock_level(item_level - 1))
    return max(50.0, gap * FIRST_ITEM_XP_SHARE)

# XP батл-пасса за мердж считается ОТДЕЛЬНО и жёстко ограничен: полный пасс
# стоит bp_total_xp(30) = 74 400, а один мердж 24 lvl давал 58 208 XP — 78%
# сезона за одно слияние (фидбек). Кап держит топ-мердж в пределах ~2% пасса.
MERGE_BP_XP_CAP = 1200

def merge_reward_bp_xp(new_level: int) -> float:
    return min(merge_reward_xp(new_level), MERGE_BP_XP_CAP)

# Рекорд тира двигает и пасс — иначе объёмный XP упал, а пасс вместе с ним.
# Кап тот же: рекорд не должен закрывать сезон в одиночку.
def first_item_bp_xp(item_level: int) -> float:
    return min(first_item_xp(item_level), MERGE_BP_XP_CAP)

# Рост дохода печеньки за уровень. РОВНО 2.0 — и это единственное значение,
# при котором экономика доски не разъезжается. Слияние съедает две печеньки,
# то есть коэффициент ветвления равен 2:
#   * база 1.7 (было когда-то) — мердж выше 12 тира УМЕНЬШАЛ доход на 15%,
#     основной цикл игры работал против игрока;
#   * база 2.15 (было до этой правки) — обратная беда: каждый следующий тир
#     окупался БЫСТРЕЕ предыдущего (4.80ч на T3 -> 1.05ч на T24), игра прямо
#     вознаграждала забег в топ-тир, и доска превращалась в печатный станок;
#   * база 2.0 — мердж строго нейтрален по доходу, а прибыль приходит из
#     ОСВОБОДИВШЕЙСЯ КЛЕТКИ. Побочный эффект самый важный: окупаемость тира
#     становится ровно ITEM_PAYBACK_HOURS на всём диапазоне, то есть эта
#     константа наконец означает то, что написано в её имени, и работает
#     единственной ручкой сложности доски.
# Дефицит держат КЛЕТКИ (их 12-25) и потолок тира по уровню игрока.
PASSIVE_GROWTH = 2.0
# База доска/ферма калибруется ПАРОЙ с таблицей FARM_BUILDINGS: доход доски
# растёт вдвое за тир, и ферма обязана расти тем же темпом, иначе одна ветка
# съедает другую (при базе 90 доска давала 1% дохода до 20 уровня, а после 26
# забирала 80%). 4000/ч на третьем тире — это доля 30-60% у доски на всей
# лестнице; менять эту константу без пересчёта cps фермы нельзя.
PASSIVE_BASE = 5500.0

def passive_income_per_hour(item_level: int) -> float:
    """Пассивный доход cookies/час от печеньки на доске.
    Единая экспонента без излома: доска маленькая (12-25 клеток) и жёстко
    ограничена уровнем игрока, поэтому разогнаться она не может физически.

    Тиры 1-2 дают ноль НАМЕРЕННО, и продолжить экспоненту вниз нельзя. Цена
    L1-спавна — почти абсолютная константа (SPAWN_L1_BASE = 50), потому что путь
    слияния стоит 2^(L-1) спавнов и любая привязка к доходу убила бы мердж-цикл.
    Дать тиру 1 доход 1375/ч при цене 50 — значит выдать окупаемость в две
    минуты, то есть печатный станок. Ноль внизу — плата за дешёвый спавн."""
    if item_level < 3:
        return 0
    return PASSIVE_BASE * (PASSIVE_GROWTH ** (item_level - 3))

